"""Tables of the manuscript (``paper/generated/tables/*.tex``, booktabs), from the registered analyses that
``scripts/paper_numbers.py`` reads and with its formats, so that a number in a table and the same number in the text
(``\\res{}``) are the same string (golden rule 1).

    python scripts/paper_tables.py

* ``tab_rq2.tex`` — H2 and H2b by cell (99.75 % Bonferroni intervals), the pooled estimates (95 %) and the
  sensitivities;
* ``tab_exact.tex`` — the exact class by cell (``t_primal``, certificates within the budget) and the delay to the first
  own solution of the three representatives (cold runs);
* ``tab_m11.tex`` — the validation of the exact stack against Bertsimas & Cory-Wright, Tables 3 and 4;
* ``tab_rq3.tex`` — H3a (TOST) and H3b (slope) by market and arm;
* ``tab_rq2_inst.tex`` — the distribution over the instances of RQ2 (medians, shares below 1, runs that never reach
  the target; §12, 2026-10-19 (1));
* ``tab_samplers.tex`` — post hoc: R and R_b with the penalty samplers in the place of the representative (§12,
  2026-10-19 (2));
* ``tab_rq3_extra.tex`` — the context of H3a that §10 asks for: the doses of rank 2, the regime of the lower bound of
  K, the block lengths and the paths after costs.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
import paper_numbers as pn

ROOT = pn.ROOT
OUT = ROOT / "paper" / "generated" / "tables"
CELL = {"C1": r"C1 & factor, $N=100$", "C2": r"C2 & factor, $N=200$", "C3": r"C3 & factor, $N=400$",
        "C4": r"C4 & S\&P 500 bootstrap, $N=200$", "C5": r"C5 & OR-Library, five ports"}
POOLED = {"primary": "Pooled (C1--C3, C5)", "without_C5": "Without C5 (post hoc)",
          "first_improvement": r"$\gamma = 1$ until the first improvement", "within_budget": "Rows within the budget",
          "own": "No common start (cold runs)", "full": r"PI over $[0, T]$ (with $t_0$)"}
SENSITIVITY_ORDER = ("primary", "without_C5", "first_improvement", "own", "full")
ROLE = {"exact_rep": "exact", "qubo_rep": "qubo", "ls": "ls"}
DENSE = {"D1_100": r"D1, $N=100$", "D1_200": r"D1, $N=200$"}


def _ci(ratio: float, low: float, high: float) -> str:
    return f"{pn.sig(ratio)} [{pn.sig(low)}, {pn.sig(high)}]"


def _write(out_dir: Path, name: str, lines: list[str]) -> Path:
    path = out_dir / name
    path.write_text("% generated by scripts/paper_tables.py; do not edit by hand.\n" + "\n".join(lines) + "\n",
                    encoding="utf-8")
    return path


def tab_rq2(out_dir: Path) -> Path:
    cells = pd.read_csv(ROOT / pn.E2_H2 / "cells.csv")
    pooled = pd.read_csv(ROOT / pn.E2_H2 / "pooled.csv")
    lines = [r"\begin{tabular}{lrll}", r"\toprule", r"Cell & $n$ & $R$ (H2) & $R_b$ (H2b) \\", r"\midrule"]
    for cell, label in CELL.items():
        part = cells[(cells.variant == "primary") & (cells.cell == cell)].set_index("hypothesis")
        h2, h2b = part.loc["H2"], part.loc["H2b"]
        n = f"{int(h2.n_instances)}" + ("" if int(h2.n_clusters) == int(h2.n_instances) else f" ({int(h2.n_clusters)})")
        cell_id = label.split(" & ", 1)[0]
        mark = "" if bool(h2.in_pooled) else r"$^{\dagger}$"
        lines.append(f"{cell_id}{mark} & {n} & {_ci(h2.ratio, h2.ratio_low, h2.ratio_high)} & "
                     f"{_ci(h2b.ratio, h2b.ratio_low, h2b.ratio_high)} \\\\")
    for cell, label in DENSE.items():  # the dense cells: descriptive by design
        part = cells[(cells.variant == "primary") & (cells.cell == cell)].set_index("hypothesis")
        if part.empty:
            continue
        h2, h2b = part.loc["H2"], part.loc["H2b"]
        lines.append(f"{label}$^{{\\dagger}}$ & {int(h2.n_instances)} & {_ci(h2.ratio, h2.ratio_low, h2.ratio_high)} & "
                     f"{_ci(h2b.ratio, h2b.ratio_low, h2b.ratio_high)} \\\\")
    lines.append(r"\midrule")
    for variant in SENSITIVITY_ORDER:
        part = pooled[pooled.variant == variant].set_index("hypothesis")
        h2, h2b = part.loc["H2"], part.loc["H2b"]
        lines.append(f"\\multicolumn{{2}}{{l}}{{{POOLED[variant]}}} & {_ci(h2.ratio, h2.ratio_low, h2.ratio_high)} & "
                     f"{_ci(h2b.ratio, h2b.ratio_low, h2b.ratio_high)} \\\\")
        if variant == "primary":
            lines.append(r"\midrule")
    # post hoc: the exact class represented by another configuration (§12, 2026-10-19), when analysed
    for name, label in (("scipaggr", "Exact: SCIP, aggressive heuristics"), ("oa", "Exact: OA in every cell")):
        source = ROOT / pn.E2_EXACT_SENS[name] / "pooled.csv"
        if not source.exists():
            continue
        frame = pd.read_csv(source)
        part = frame[frame.variant == "primary"].set_index("hypothesis")
        h2, h2b = part.loc["H2"], part.loc["H2b"]
        lines.append(f"\\multicolumn{{2}}{{l}}{{{label}}} & {_ci(h2.ratio, h2.ratio_low, h2.ratio_high)} & "
                     f"{_ci(h2b.ratio, h2b.ratio_low, h2b.ratio_high)} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    return _write(out_dir, "tab_rq2.tex", lines)


def tab_exact(out_dir: Path) -> Path:
    exact = pd.read_csv(ROOT / pn.E2_SECONDARY / "exact_times.csv").set_index("cell")
    delay = pd.read_csv(ROOT / pn.E2_DELAY / "delay_cells.csv")
    names = {"scip-persp-mineig-sym0": "SCIP", "oa-highs": "OA (HiGHS)"}
    lines = [r"\begin{tabular}{llrrrrr}", r"\toprule",
             r"Cell & exact method & $t_{\mathrm{primal}}$ (s) & certified (\%) & "
             r"\multicolumn{3}{c}{first own solution (s)} \\",
             r"\cmidrule(lr){5-7}", r" & & & & QUBO & LS & exact \\", r"\midrule"]
    for cell, label in CELL.items():
        row = exact.loc[cell]
        d = {ROLE[r.role]: pn.sig(r.median_s, 2) for r in delay[delay.cell == cell].itertuples()}
        mark = r"$^{\dagger}$" if cell == "C4" else ""  # the descriptive cell
        lines.append(f"{label.split(' & ', 1)[0]}{mark} & {names.get(row.configs, row.configs)} & {pn.sig(row.t_primal_median, 2)} & "
                     f"{pn.pct(row.share_in_budget)} & {d['qubo']} & {d['ls']} & {d['exact']} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    return _write(out_dir, "tab_exact.tex", lines)


def tab_m11(out_dir: Path) -> Path:
    report = json.loads((ROOT / pn.E2_M11 / "m11.json").read_text(encoding="utf-8"))
    cells = pd.read_csv(ROOT / pn.E2_M11 / "cells.csv")
    lines = [r"\begin{tabular}{lrrrrrrr}", r"\toprule",
             r" & \multicolumn{3}{c}{median ratio} & \multicolumn{2}{c}{median time (s)} & \multicolumn{2}{c}{solved} \\",
             r"\cmidrule(lr){2-4}\cmidrule(lr){5-6}\cmidrule(lr){7-8}",
             r"BCW table & SCIP & OA & best of ours & SCIP & BCW best & ours & BCW \\", r"\midrule"]
    for table, block in report["tables"].items():
        s = block["summary"]
        oa = pn.sig(s["oa"]["median_ratio"], 2) if "oa" in s and s["oa"]["median_ratio"] is not None else "--"
        mine = cells[cells.table == table]
        lines.append(f"BCW-{table} & "
                     f"{pn.sig(s['scip']['median_ratio'], 2)} & {oa} & {pn.sig(s['stack']['median_ratio'], 2)} & "
                     f"{pn.sig(float(mine.scip_time_s.median()), 2)} & {pn.sig(float(mine.published_best_s.median()), 2)} & "
                     f"{s['scip']['n_ours_solved']}/{s['scip']['n_cells']} & "
                     f"{s['scip']['n_pub_solved']}/{s['scip']['n_cells']} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    return _write(out_dir, "tab_m11.tex", lines)


def tab_rq3(out_dir: Path) -> Path:
    analysis = json.loads((ROOT / pn.E3_ANALYSIS / "tables" / "analysis.json").read_text(encoding="utf-8"))
    names = {"ff49-MV": r"FF49, MV", "ff49-GMV": r"FF49, GMV", "us-MV": r"US, MV", "us_irregular-MV": r"US, MV$^{\ddagger}$"}
    outcome = {"equivalent": "equivalent", "inconclusive": "inconclusive", "different": "different"}
    primary = analysis["arms"]["ff49-MV"]
    level_a = pn.pct(1 - 2 * primary["h3a"]["alpha"])  # TOST at α: the (1 − 2α) interval
    lines = [r"\begin{tabular}{lllll}", r"\toprule",
             f"Market, arm & estimate [{level_a}\\% CI] & margin & $p_{{\\mathrm{{TOST}}}}$ & outcome \\\\",
             r"\midrule"]
    for arm, label in names.items():
        part = analysis["arms"][arm]
        h3a = part["h3a"]
        holm = analysis.get("h3a_holm", {}).get(arm)
        p = pn.pval(holm["pvalue_tost_holm"]) + r"$^{*}$" if holm else pn.pval(h3a["pvalue_tost"])
        lo_m, hi_m = h3a["margin"]
        margin = f"$\\pm${pn.sig(hi_m)}" if abs(lo_m + hi_m) < 1e-12 else f"[{pn.sig(lo_m)}, {pn.sig(hi_m)}]"
        lines.append(f"{label} & {pn.sig(h3a['estimate'])} [{pn.sig(h3a['ci_tost'][0])}, {pn.sig(h3a['ci_tost'][1])}] & "
                     f"{margin} & {p} & {outcome.get(h3a['outcome'], h3a['outcome'])} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    return _write(out_dir, "tab_rq3.tex", lines)


def _max_ratio(x: float) -> str:
    return pn.median_count(x) if x >= 100 else pn.sig(x, 2)


def tab_rq2_inst(out_dir: Path) -> Path:
    """The distribution over the instances behind the pooled ratios (§12, 2026-10-19 (1)): the medians and the shares
    below 1 of R and R_b, the largest R_b, and the instances on which the Kaplan-Meier median of the time to the target
    is beyond the budget."""
    inst = pd.read_csv(ROOT / pn.E2_H2 / "instances.csv")
    cens = pd.read_csv(ROOT / pn.E2_SECONDARY / "ttt_censoring.csv")
    cens = cens[cens.variant == "primary"].set_index("cell")
    lines = [r"\begin{tabular}{lrrrrrrrrr}", r"\toprule",
             r" & & \multicolumn{2}{c}{$R$} & \multicolumn{3}{c}{$R_b$} & \multicolumn{3}{c}{target not reached} \\",
             r"\cmidrule(lr){3-4}\cmidrule(lr){5-7}\cmidrule(lr){8-10}",
             r"Cell & $n$ & median & $<1$ (\%) & median & $<1$ (\%) & max & QUBO & LS & exact \\", r"\midrule"]
    labels = {**{c: lab.split(" & ", 1)[0] + ("$^{\\dagger}$" if c == "C4" else "") for c, lab in CELL.items()},
              **{c: f"{lab}$^{{\\dagger}}$" for c, lab in DENSE.items()}}
    for cell, label in labels.items():
        g = inst[inst.cell == cell]
        if g.empty:
            continue
        c = cens.loc[cell]
        lines.append(f"{label} & {len(g)} & {pn.sig(float(g.r.median()), 2)} & {pn.pct(float((g.r < 1).mean()))} & "
                     f"{pn.sig(float(g.r_b.median()), 2)} & {pn.pct(float((g.r_b < 1).mean()))} & "
                     f"{_max_ratio(float(g.r_b.max()))} & {int(c.censored_qubo)} & {int(c.censored_ls)} & "
                     f"{int(c.censored_exact)} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    return _write(out_dir, "tab_rq2_inst.tex", lines)


def tab_samplers(out_dir: Path) -> Path:
    """Post hoc (§12, 2026-10-19 (2)): the same estimator with the penalty samplers of the same runs in the place of the
    representative (swap-SA); cells at their point estimates, the pooled rows with their 95 % intervals."""
    sources = {"swap-SA": pn.E2_H2, "SA": pn.E2_H2_SA, "tabu": pn.E2_H2_TABU}
    cells = {k: pd.read_csv(ROOT / v / "cells.csv") for k, v in sources.items()}
    pooled = {k: pd.read_csv(ROOT / v / "pooled.csv") for k, v in sources.items()}
    lines = [r"\begin{tabular}{lllllll}", r"\toprule",
             r" & \multicolumn{3}{c}{$R$ (against the exact class)} & \multicolumn{3}{c}{$R_b$ (against local search)} \\",
             r"\cmidrule(lr){2-4}\cmidrule(lr){5-7}",
             r"Cell & swap-SA & SA & tabu & swap-SA & SA & tabu \\", r"\midrule"]

    def value(frame, cell, hypothesis):
        row = frame[(frame.variant == "primary") & (frame.cell == cell) & (frame.hypothesis == hypothesis)].iloc[0]
        return pn.sig(float(row.ratio))

    for cell, label in CELL.items():
        mark = "" if cell != "C4" else r"$^{\dagger}$"
        parts = [value(cells[k], cell, h) for h in ("H2", "H2b") for k in sources]
        lines.append(f"{label.split(' & ', 1)[0]}{mark} & " + " & ".join(parts) + r" \\")
    lines.append(r"\midrule")
    for hypothesis_row in ("estimate", "interval"):
        parts = []
        for h in ("H2", "H2b"):
            for k in sources:
                row = pooled[k][(pooled[k].variant == "primary") & (pooled[k].hypothesis == h)].iloc[0]
                parts.append(pn.sig(float(row.ratio)) if hypothesis_row == "estimate" else
                             f"[{pn.sig(float(row.ratio_low))}, {pn.sig(float(row.ratio_high))}]")
        label = "Pooled" if hypothesis_row == "estimate" else r"95\% CI"  # num-ok: level of the pooled interval (pooled over C1-C3, C5)
        lines.append(f"{label} & " + " & ".join(parts) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    return _write(out_dir, "tab_samplers.tex", lines)


def tab_rq3_extra(out_dir: Path) -> Path:
    """What §10 asks to report with H3a: the in-sample dose of the rank-2 path (bp of CE per year), the share of the
    folds where the lower bound of K is active (K·u ≈ 1), the calibrated block length and the difference of Sharpe
    ratios of the rank-2 path after costs (10 and 30 bp per unit of turnover) with its 95 % interval."""
    analysis = json.loads((ROOT / pn.E3_ANALYSIS / "tables" / "analysis.json").read_text(encoding="utf-8"))
    net = pd.read_csv(ROOT / pn.E3_ANALYSIS / "tables" / "net_differences.csv")
    arms = {"ff49-MV": ("ff49", "MV", r"FF49, MV"), "ff49-GMV": ("ff49", "GMV", r"FF49, GMV"),
            "us-MV": ("us", "MV", r"US, MV")}
    # the share of folds at the lower bound of K and the block lengths are in the text (keys of paper_numbers)
    lines = [r"\begin{tabular}{llll}", r"\toprule",
             r"Market, arm & dose of rank 2 (bp) & \multicolumn{2}{c}{$\Delta$Sharpe after costs [95\% CI]} \\",  # num-ok: confidence level of the bootstrap
             r"\cmidrule(lr){3-4}", r" & median [IQR] & 10~bp & 30~bp \\", r"\midrule"]  # num-ok: cost levels of the plan
    for key, (market, arm, label) in arms.items():
        dose = next(d for d in analysis["describe"][market]["rank2_doses"] if d["arm"] == arm and d["stratum"] == "all")
        cols = []
        for cost in ("cost_10", "cost_30"):
            row = net[(net.key == key) & (net.path == "rank_2") & (net.cost == cost)].iloc[0]
            cols.append(f"{pn.sig(float(row.sharpe_diff), 2)} [{pn.sig(float(row.sharpe_diff_lo), 2)}, "
                        f"{pn.sig(float(row.sharpe_diff_hi), 2)}]")
        lines.append(f"{label} & {pn.sig(dose['median'], 2)} [{pn.sig(dose['q1'], 2)}, {pn.sig(dose['q3'], 2)}] & "
                     f"{cols[0]} & {cols[1]} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    return _write(out_dir, "tab_rq3_extra.tex", lines)


TABLES = (tab_rq2, tab_exact, tab_m11, tab_rq3, tab_rq2_inst, tab_samplers, tab_rq3_extra)


def main(out_dir: Path | None = None) -> list[Path]:
    out_dir = Path(out_dir) if out_dir is not None else OUT
    out_dir.mkdir(parents=True, exist_ok=True)
    written = [table(out_dir) for table in TABLES]
    print(", ".join(p.name for p in written))
    return written


if __name__ == "__main__":
    main()
